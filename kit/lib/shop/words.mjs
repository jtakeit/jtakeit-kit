/**
 * The storefront's words for a page's language, as a fresh object the caller
 * may write over. A regional tag reads its language's words (`de-CH` is
 * German, `pt-BR` Portuguese); any language the kit has no words in reads
 * English, as the booking form does.
 *
 * @param {string | undefined} locale a tag such as `de`, `fr-CH`; anything else reads as `en`
 * @returns {Record<string, string>}
 */
export function shopWordsFor(locale) {
  const plain = String(locale ?? '').split('-')[0].toLowerCase();
  return { ...BASE[SHOP_LOCALES.includes(plain) ? plain : 'en'] };
}
