/**
 * The storefront's words, per language: what the product page, the cart, the
 * checkout step and the page after payment say, in the kit's eight languages
 * (the booking form's), English for any other.
 *
 * A site's copied components draw their own labels from here and hand the
 * same words to the element as `data-words`, so the markup and the element
 * say one thing. A word may hold a placeholder in braces, `{n}` and the like,
 * the same in every language; a test holds every language to every key and
 * to the same placeholders (kit/test/shop.test.mjs), as the booking form's
 * are held.
 *
 * Three groups are fixed by the protocol and not invented here: `refused.*`
 * are the codes of a line the shop will not price (`not_sold`, `off_sale`,
 * `quantity`, `answer`, `too_large`), `state.*` the order page's states and
 * what is said while it waits, and `error.*` the checkout's refusals, each by
 * the name the protocol gives it (docs/reference/shop-protocol.md of the
 * platform). `fault.*` are what a field says: an answer to a customization
 * (`required`, `too_long`, `not_a_choice`) and a buyer's detail by the field's
 * name. A price's qualifiers («from {amount}») are `priceWords` in
 * money.mjs, which every price on a site shares.
 *
 * A word that is one sentence has no full stop at the end: the markup it is
 * written into may add its own, and a word the English of which the spec fixes
 * is exactly as the spec wrote it. A regional tag reads its language's words,
 * as it does for a price (`de-CH` is German).
 *
 * Plain on purpose: a native speaker reads them before a site goes live.
 */

